// Deterministic mock AI provider for the demo endpoints.
// Every result is labelled mock. It never pretends to be a real model.
import { validateChangePlan } from './validate.mjs';

let counter = 0;
function nextId(prefix) { counter += 1; return 'el-ai-' + prefix + '-' + counter + '-' + Date.now().toString(36); }

export function generateMockPlan(prompt, registry) {
  const lower = String(prompt || '').toLowerCase();
  const ops = [];
  if (lower.includes('faq')) {
    ops.push({ type: 'add_element', element: { id: nextId('faq'), componentId: 'section.faq', props: { heading: 'Frequently asked questions', items: [{ question: 'Sample question from the mock provider', answer: 'Sample answer. Replace with real content.' }] } } });
  } else if (lower.includes('testimonial')) {
    ops.push({ type: 'add_element', element: { id: nextId('testimonials'), componentId: 'section.testimonials', props: { heading: 'Sample feedback', items: [{ quote: 'Sample quote from the mock provider.', name: 'Sample Person', role: 'Sample role' }] } } });
  } else if (lower.includes('cta') || lower.includes('call to action')) {
    ops.push({ type: 'add_element', element: { id: nextId('cta'), componentId: 'section.cta', props: { heading: 'Ready to start?', text: 'Generated by the mock provider.', ctaLabel: 'Get started', ctaHref: '/builder' } } });
  } else if (lower.includes('landing') || lower.includes('page')) {
    ops.push({ type: 'add_element', element: { id: nextId('hero'), componentId: 'section.hero', props: { heading: 'A new page from the mock provider', subheading: 'This structure was generated deterministically for the demo.', ctaLabel: 'Get started', ctaHref: '/builder' } } });
    ops.push({ type: 'add_element', element: { id: nextId('features'), componentId: 'section.feature-grid', props: { heading: 'Highlights', items: [{ title: 'One', text: 'Sample feature.' }, { title: 'Two', text: 'Sample feature.' }, { title: 'Three', text: 'Sample feature.' }] } } });
  } else {
    ops.push({ type: 'add_element', element: { id: nextId('heading'), componentId: 'content.heading', props: { text: 'Generated heading', level: 2, align: 'left' } } });
    ops.push({ type: 'add_element', element: { id: nextId('text'), componentId: 'content.rich-text', props: { html: '<p>Generated by the mock provider from your prompt. Review and edit before publishing.</p>' } } });
  }
  const plan = { summary: 'Mock plan with ' + ops.length + ' operation(s). Review before applying.', operations: ops };
  const check = validateChangePlan(plan, registry);
  return { provider: 'mock', mock: true, plan, validation: check };
}

export function editMockPlan(instruction, element) {
  const lower = String(instruction || '').toLowerCase();
  let props = {};
  if (element && element.componentId === 'content.heading') {
    props = { text: lower.includes('shorten') ? 'Shorter heading' : 'Edited heading (mock)' };
  } else if (element && element.componentId === 'section.hero') {
    props = { subheading: 'Edited by the mock provider. Review before applying.' };
  } else {
    props = {};
  }
  const plan = { summary: 'Mock edit plan. Review before applying.', operations: element ? [{ type: 'update_element_props', elementId: element.id, componentId: element.componentId, props }] : [] };
  return { provider: 'mock', mock: true, plan };
}

export function proposeComponentSchema(prompt) {
  // Phase 11: schema proposal only. Registration requires human approval and
  // stores a schema, never executable code.
  return {
    provider: 'mock', mock: true, requiresApproval: true,
    schema: { id: 'custom.proposed-element', version: '0.1.0', category: 'custom', label: 'Proposed element', props: { title: { type: 'string', default: 'Title', required: true }, text: { type: 'string', default: '' } } },
    note: 'Proposal only. A human must approve before this schema can be registered. No code is generated or executed.',
  };
}
