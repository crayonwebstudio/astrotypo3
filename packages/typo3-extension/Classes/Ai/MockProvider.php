<?php
declare(strict_types=1);
namespace Crayonwebstudio\AstroBuilder\Ai;

/**
 * Deterministic mock provider. Labelled as mock in every response.
 * Used for tests and local development. Never presented as a real AI.
 */
final class MockProvider implements AiProviderInterface
{
    public function getName(): string
    {
        return 'mock';
    }

    public function generateChangePlan(string $prompt, array $context): array
    {
        $lower = strtolower($prompt);
        $componentId = 'section.hero';
        if (str_contains($lower, 'faq')) {
            $componentId = 'section.faq';
        } elseif (str_contains($lower, 'cta') || str_contains($lower, 'call to action')) {
            $componentId = 'section.cta';
        }
        return [
            'provider' => 'mock',
            'mock' => true,
            'plan' => [
                'summary' => 'Mock plan: add one ' . $componentId . ' element. Review before applying.',
                'operations' => [
                    [
                        'type' => 'add_element',
                        'element' => [
                            'id' => 'el-ai-' . substr(hash('sha256', $prompt), 0, 8),
                            'componentId' => $componentId,
                            'props' => ['heading' => 'Generated by the mock provider'],
                        ],
                    ],
                ],
            ],
        ];
    }
}
